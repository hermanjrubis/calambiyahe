/**
 * Builds public/css/account-modals-planner.css from the account-modal section of style.css.
 *
 * The planner does not load style.css (it would change the planner layout), so the account
 * modals (My Visits, My Trips, Saved Places, My Badges) had no styles there. This copies the
 * "CALZADA UNIFIED MODAL & CARD DESIGN SYSTEM" section, scopes every selector to
 * `.planner-body #calzadaModalsRoot` (so planner elements that reuse a class name, such as the
 * sign-in modal's .modal-close-btn, are untouched) and swaps gradients for solid colours.
 *
 * Run after changing that section of style.css:  node scripts/build-planner-account-modals-css.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const css = fs.readFileSync(path.join(root, 'public/css/style.css'), 'utf8');
const START = 'CALZADA UNIFIED MODAL & CARD DESIGN SYSTEM';
const END = '/* Settings Box';
const scope = '.planner-body #calzadaModalsRoot';

const startIdx = css.lastIndexOf('/*', css.indexOf(START));
const endIdx = css.indexOf(END, startIdx);
if (startIdx < 0 || endIdx < 0) throw new Error('style.css section markers not found');
const section = css.slice(startIdx, endIdx);

// Gradients -> solid: background-image gradients are dropped (the background-color stays);
// a gradient shorthand becomes its first colour.
const solidify = (decls) => decls.replace(/(^|;|\{|\n)(\s*)(background(?:-image)?)\s*:\s*([^;]*gradient\([^;]*);/g,
    (m, pre, ws, prop, value) => {
        if (prop === 'background-image') return `${pre}${ws}background-image: none;`;
        const color = (value.match(/#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/) || ['transparent'])[0];
        return `${pre}${ws}background: ${color};`;
    });

const prefixSelectors = (sel) => sel.split(',').map(s => {
    const t = s.trim();
    return t ? `${scope} ${t}` : t;
}).join(',\n');

// Minimal block walker: comments, @media (recursed), @keyframes (copied as is), rules.
function transform(src) {
    let out = '';
    let i = 0;
    while (i < src.length) {
        if (src.startsWith('/*', i)) {
            const j = src.indexOf('*/', i + 2) + 2;
            out += src.slice(i, j);
            i = j;
            continue;
        }
        if (/\s/.test(src[i])) { out += src[i++]; continue; }
        const open = src.indexOf('{', i);
        if (open < 0) { out += src.slice(i); break; }
        const head = src.slice(i, open);
        // matching close brace
        let depth = 1, k = open + 1;
        while (depth && k < src.length) {
            if (src.startsWith('/*', k)) { k = src.indexOf('*/', k + 2) + 2; continue; }
            if (src[k] === '{') depth++;
            else if (src[k] === '}') depth--;
            k++;
        }
        const body = src.slice(open + 1, k - 1);
        const h = head.trim();
        if (h.startsWith('@keyframes')) {
            out += `${h} {${body}}`;
        } else if (h.startsWith('@media') || h.startsWith('@supports')) {
            out += `${h} {${transform(body)}}`;
        } else {
            out += `${prefixSelectors(h)} {${solidify(body)}}`;
        }
        i = k;
    }
    return out;
}

const header = `/* GENERATED by scripts/build-planner-account-modals-css.js from style.css
   ("CALZADA UNIFIED MODAL & CARD DESIGN SYSTEM" section). Do not edit by hand.
   Planner only: account modals scoped to ${scope}; gradients replaced with solid colours. */

`;
const outPath = path.join(root, 'public/css/account-modals-planner.css');
fs.writeFileSync(outPath, header + transform(section).trim() + '\n');
console.log(`wrote ${path.relative(root, outPath)} (${section.split('\n').length} source lines)`);
